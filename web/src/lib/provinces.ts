export function getProvinceByCode(code: string): Province | undefined {
  return PROVINCES.find((p) => p.code === code);
}

export function getShippingFeeForProvince(provinceCode: string, shopCount = 1): number {
  const province = getProvinceByCode(provinceCode);
  const base = province ? province.shippingFee : 28000;
  // Multi-shop consolidated fee: first shop full rate, each additional shop +12.000₫
  const extraShops = Math.max(0, shopCount - 1);
  return base + extraShops * 12000;
}
