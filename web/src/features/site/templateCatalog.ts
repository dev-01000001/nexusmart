export function findPlatformTemplate(idOrSlug: string): PlatformTemplateDTO | undefined {
  const clean = idOrSlug.trim().toLowerCase();
  return PLATFORM_TEMPLATES.find((t) => t.id === clean || t.slug === clean);
}

/** Deep-clones a template config and applies the shop's brand identity cleanly. */
export function cloneTemplateConfigForShop(
  template: PlatformTemplateDTO,
  opts: { brandName?: string; tagline?: string; logoUrl?: string } = {}
): SiteTemplateConfig {
  const cloned = JSON.parse(JSON.stringify(template.config)) as SiteTemplateConfig;
  if (opts.brandName?.trim()) {
    cloned.theme.brand_name = opts.brandName.trim().slice(0, 80);
  }
  if (opts.tagline?.trim()) {
    cloned.theme.tagline = opts.tagline.trim().slice(0, 160);
  }
  if (opts.logoUrl?.trim()) {
    cloned.theme.logo_url = opts.logoUrl.trim();
  }
  return cloned;
}
